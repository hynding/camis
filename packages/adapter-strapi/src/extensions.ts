import { stableJson, type GeneratedFile } from "@camis/adapter-kernel";

export const USERS_PERMISSIONS_EXTENSION_PATH = "src/extensions/users-permissions/strapi-server.ts";

// Indent an emitted JSON block to sit inside a function body, without touching its first line.
const indented = (json: string): string =>
  json
    .trimEnd()
    .split("\n")
    .map((line, i) => (i === 0 || line === "" ? line : `  ${line}`))
    .join("\n");

/**
 * The plugin extension that gives Strapi's users-permissions `user` content type the inverse
 * attributes an IR relation names on it.
 *
 * That content type belongs to a plugin, so this generator writes no schema.json for it and has
 * nowhere else to put the inverse. Strapi refuses to boot on the resulting dangling `inversedBy`,
 * and a relation Strapi does not know is two-sided also loses the `_ord` column its link table
 * needs. Strapi's shallow-merges a `content-types/**\/schema.json` extension over the plugin's
 * own — which would mean restating the whole user schema — so the `strapi-server` hook, which
 * mutates the loaded plugin, is the form that stays version-independent.
 */
export const usersPermissionsExtensionFile = (
  attributes: Record<string, unknown>,
): GeneratedFile => ({
  path: USERS_PERMISSIONS_EXTENSION_PATH,
  content: `// @camis:generated — do not edit; regenerated by camis
interface UsersPermissionsPlugin {
  contentTypes: { user: { schema: { attributes: Record<string, unknown> } } };
}

export default (plugin: UsersPermissionsPlugin): UsersPermissionsPlugin => {
  Object.assign(plugin.contentTypes.user.schema.attributes, ${indented(stableJson(attributes))});

  return plugin;
};
`,
});
