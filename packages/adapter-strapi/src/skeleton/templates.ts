const CONDITIONS_IMPORT = `import { conditions } from "./permissions/conditions";\n`;
const REGISTER_CONDITIONS = `    await strapi.admin.services.permission.conditionProvider.registerMany(conditions);\n`;

/**
 * The bootstrap that seeds roles. It imports and registers the conditions module only when the
 * project emits one: an import of a module that is not there stops Strapi from booting.
 */
export const permissionsIndexTs = (
  withConditions: boolean,
): string => `${withConditions ? CONDITIONS_IMPORT : ""}import roles from "./permissions/roles.json";
import apiRoles from "./permissions/api-roles.json";

export default {
  async register() {},
  async bootstrap({ strapi }: { strapi: any }) {
${withConditions ? REGISTER_CONDITIONS : ""}    for (const role of roles) {
      const existing = await strapi.query("admin::role").findOne({ where: { name: role.name } });
      const record = existing ?? (await strapi.query("admin::role").create({ data: { name: role.name, description: role.description } }));
      for (const p of role.permissions) {
        // Explicit even when empty: Strapi 5's query engine binds the json default unserialised,
        // which sqlite refuses.
        await strapi.query("admin::permission").create({ data: { conditions: [], ...p, role: record.id } });
      }
    }
    // The plugin actions an earlier boot of this bootstrap created, per role type, kept in
    // Strapi's core store: only those are camis's to revoke. Every other "plugin::" row is
    // Strapi's own default (users-permissions' user.me, the auth endpoints) or an
    // administrator's, and deleting those would break login, or undo a deliberate grant.
    const store = strapi.store({ type: "plugin", name: "camis" });
    const stored = await store.get({ key: "granted-plugin-actions" });
    const granted: Record<string, string[]> = stored !== null && typeof stored === "object" ? stored : {};
    const grantedTo = (type: string): string[] =>
      Object.prototype.hasOwnProperty.call(granted, type) && Array.isArray(granted[type]) ? granted[type] : [];
    const grant = async (type: string, actions: string[], create = true) => {
      let role = await strapi.query("plugin::users-permissions.role").findOne({ where: { type } });
      if (!role && !create) return;
      if (!role) role = await strapi.query("plugin::users-permissions.role").create({ data: { name: type, type, description: "camis" } });
      const mine = new Set<string>(grantedTo(type));
      for (const action of actions) {
        const existing = await strapi.query("plugin::users-permissions.permission").findOne({ where: { action, role: role.id } });
        if (existing) continue;
        await strapi.query("plugin::users-permissions.permission").create({ data: { action, role: role.id } });
        if (!action.startsWith("api::")) mine.add(action);
      }
      // Revoke what camis no longer grants. Without this, a grant deleted from the IR survives in
      // any database an earlier generation already seeded. Every "api::" row is camis's; a
      // "plugin::" row only when this bootstrap created it.
      const owned = await strapi.query("plugin::users-permissions.permission").findMany({ where: { role: role.id } });
      for (const p of owned) {
        if (typeof p.action !== "string") continue;
        if (!p.action.startsWith("api::") && !mine.has(p.action)) continue;
        if (actions.includes(p.action)) continue;
        await strapi.query("plugin::users-permissions.permission").delete({ where: { id: p.id } });
        mine.delete(p.action);
      }
      granted[type] = [...mine].sort();
    };
    // The public role in one pass: its registration actions beside its own grants, so neither
    // revokes the other.
    const publicGrants = apiRoles.roles.find((r) => r.type === "public")?.actions ?? [];
    await grant("public", [...apiRoles.public, ...publicGrants]);
    for (const r of apiRoles.roles) if (r.type !== "public") await grant(r.type, r.actions);
    // A role type taken out of the IR: revoke all an earlier boot granted it, then forget it.
    // The role itself stays (users may hold it); one already deleted is not created again.
    const current = new Set<string>(["public", ...apiRoles.roles.map((r) => r.type)]);
    for (const type of Object.keys(granted)) {
      if (current.has(type)) continue;
      await grant(type, [], false);
      delete granted[type];
    }
    await store.set({ key: "granted-plugin-actions", value: granted });
  },
};
`;
